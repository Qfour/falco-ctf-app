#!/usr/bin/env bash
# Deploy or upgrade a single CTF user's environment.
#
# Pods are immutable on the volume / container fields — `helm upgrade` cannot
# rotate them in place. This wrapper deletes the workspace Pod when a chart
# upgrade is detected so Helm always reaches the desired state.
#
# Per-challenge values.yaml (postStart) lives in this repo's challenges/; pass
# --challenges-dir to point elsewhere. Fixtures are image-baked (only
# <id>/fixtures/**; ADR-0026 / I16).
#
# Usage:
#   [FALCO_CTF_REGISTRY=<registry>/<prefix>] [FALCO_CTF_IMAGE_TAG=<tag>] \
#   deploy-user.sh [--challenges-dir <path>] [--scenarios-dir <path>] \
#                  [--flags-file <path>] [--dns-suffix <suffix>] \
#                  [--frame-ancestors <'none'|https://host>] [--app-host <host>] \
#                  [--egress-lockdown --api-server-cidr <cidr>] \
#                  <username> <challenge-id>
#
# <challenge-id> is one of three modes (P27-1, REFACTORING.md, added the
# third). Anything else exits 2 before any kubectl / helm call (app#494):
# <NN-slug> must match challengeid.Pattern, a scenario name must match
# SCENARIO_PATTERN (both literals are below, next to the checks).
#   all               — every challenge's plant/fixtures (challenges/values-all.yaml).
#   <NN-slug>          — a single challenge (challenges/<id>/values.yaml if present).
#   scenario:<name>    — ONLY the challenges listed in
#                        <scenarios-dir>/<name>/scenario.yaml's `challenges:`
#                        list get their flag planted/mount bound AND are
#                        visible under /opt/ctf/missions/ in the participant
#                        shell (challenges/values-scenario-<name>.yaml,
#                        GENERATED by challenges/gen-values.sh — run
#                        `make gen-values` after adding/editing a
#                        scenarios/<name>/scenario.yaml). An id NOT in that
#                        list is unreachable — no flag, no fixtures, no
#                        README — regardless of what "all" mode would plant.
#
# --dns-suffix <suffix>, --api-server-cidr <cidr>, and the env FALCO_CTF_REGISTRY /
#   FALCO_CTF_IMAGE_TAG are checked against a closed grammar before any kubectl / helm
#   call (exit 2, `invalid <name>: ...`; app#510) and passed to helm with --set-string.
#   The literals and what each accepts are next to the checks (DNS_SUFFIX_PATTERN,
#   REGISTRY_PATTERN, IMAGE_TAG_PATTERN, API_SERVER_CIDR_PATTERN): a DNS subdomain
#   (<= 253 characters, lower case), an OCI host[:port]/path ending in /falco-ctf (the
#   scoreboard ingest filter), an OCI tag, an IPv4 a.b.c.d/n.
#
# --scenarios-dir <path>: where scenario:<name> resolves <name>/scenario.yaml
#   from. Defaults to the sibling `scenarios/` dir at the repo root (this
#   chart lives at charts/ctf-user). Only used for scenario:<name> deploys.
#
# --flags-file <path>: decrypted events flags.yaml ({flags: {id: FALCO{...}}}).
#   Overrides the chart's FALCO{dev-...} defaults with real per-event flags.
#   Fail-closed (validate-flags-file.sh): the file must supply a flag for
#   EVERY evade challenge this deploy plants (all → all of them;
#   scenario:<name> → the scenario's; <NN-slug> → that one); values must
#   match FALCO{...} (only A-Za-z0-9_- inside the braces), differ from every repository/chart default
#   and from each other. Otherwise the script exits non-zero before touching
#   the cluster. Only the in-scope entries are passed to helm.
#   Omit for local dev (dev placeholders are used, nothing is validated).
#
# --frame-ancestors <value>: CSP `frame-ancestors` source the ttyd-proxy
#   sidecar (P23-3) stamps on every ttyd response. Set this to the portal's
#   OWN origin (P23-4 embeds ttyd in the portal's Terminal tab via iframe),
#   e.g. "https://app.<dns-suffix>" (the participant host serving /portal).
#   Exactly one source: "'none'" (with its quotes) or https://<host> (lower case,
#   no port or path; at most 261 characters), else exit 2 before any kubectl /
#   helm call (ADR-0044). With --app-host, a value other than 'none' must be
#   exactly https://<app-host>. Omit to keep the chart's fail-safe default
#   ('none' — nobody may frame ttyd), which is correct if the portal is not
#   deployed/reachable yet.
#
# --app-host <host>: bare host (no scheme; the --dns-suffix grammar: lower case
#   RFC 1123 name, no port or path, at most 253 characters; else exit 2, ADR-0044)
#   of the single-origin participant
#   app (P19-2b, e.g. "app.<dns-suffix>") that fronts oauth2-proxy's
#   /oauth2/start sign-in page. Used ONLY to build the unauthenticated ttyd
#   Ingress's `auth-signin` redirect target (chart's `auth.authSignin`) — it
#   does not touch the roster check (I8). Omit to keep the
#   chart's `auth.<dns-suffix>` compat-bridge default (app#99 follow-up:
#   pass this once the platform-side bridge Ingress is ready to retire).
#
# --egress-lockdown: turn on the ctf-user egress NetworkPolicy (P11.5). The
#   workspace can then only reach the collector + kube-dns + the API server;
#   the scoreboard is unreachable directly (webhook-forge防止). Requires
#   --api-server-cidr. Omit for local demo (egress open, non-destructive).
# --api-server-cidr <cidr>: apiserver endpoint CIDR the workspace needs for
#   ttyd's `kubectl exec` (e.g. 10.100.0.1/32 in prod EKS). Only used with
#   --egress-lockdown. Get it from terraform output on the platform side.
#   NOTE (ADR-WS-0005 enforcement fix, 2026-09-01): this CIDR alone is NOT
#   sufficient once the cluster's NetworkPolicy agent enforces egress —
#   in-cluster kubectl always dials the `kubernetes.default` Service
#   ClusterIP, not the real apiserver address this CIDR authorizes. This
#   script derives that ClusterIP itself (`kubectl get svc kubernetes -n
#   default`) and adds it as a second, narrower egress rule automatically —
#   no separate flag needed, but --egress-lockdown now also requires kubectl
#   access to the target cluster's `default` namespace.
#
# Env override:
#   FALCO_CTF_CHALLENGES_DIR=<path>   (lower precedence than --challenges-dir)
#
# Defaults to <repo-root>/challenges (this chart lives at charts/ctf-user).
#
# Display name:
#   `--display-name` was REMOVED (ADR-0034 D10 / D12): passing it exits 2
#   with the reason, before any kubectl/helm call. This script no longer
#   writes a display name at all — the initial name is the user's seat, and a
#   participant changes it (and picks an avatar) in the portal's Me screen.
set -euo pipefail

# Chart lives at <app-repo>/charts/ctf-user; challenges/ is a sibling under the
# same repo root. (Moved here from falco-ctf-platform in P2 so the per-user
# deploy no longer depends on a separate app-repo checkout.)
CHART_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${CHART_DIR}/../.." && pwd)"
DEFAULT_CHALLENGES_DIR="${REPO_ROOT}/challenges"
DEFAULT_SCENARIOS_DIR="${REPO_ROOT}/scenarios"

CHALLENGES_DIR=""
SCENARIOS_DIR=""
FLAGS_FILE=""
DNS_SUFFIX=""
FRAME_ANCESTORS=""
APP_HOST=""
EGRESS_LOCKDOWN=0
API_SERVER_CIDR=""
POSITIONAL=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --challenges-dir)
      CHALLENGES_DIR="${2:?--challenges-dir requires a path}"; shift 2 ;;
    --challenges-dir=*)
      CHALLENGES_DIR="${1#--challenges-dir=}"; shift ;;
    --scenarios-dir)
      SCENARIOS_DIR="${2:?--scenarios-dir requires a path}"; shift 2 ;;
    --scenarios-dir=*)
      SCENARIOS_DIR="${1#--scenarios-dir=}"; shift ;;
    --dns-suffix)
      DNS_SUFFIX="${2:?--dns-suffix requires a value}"; shift 2 ;;
    --dns-suffix=*)
      DNS_SUFFIX="${1#--dns-suffix=}"; shift ;;
    --frame-ancestors)
      FRAME_ANCESTORS="${2:?--frame-ancestors requires a value}"; shift 2 ;;
    --frame-ancestors=*)
      FRAME_ANCESTORS="${1#--frame-ancestors=}"; shift ;;
    --app-host)
      APP_HOST="${2:?--app-host requires a value}"; shift 2 ;;
    --app-host=*)
      APP_HOST="${1#--app-host=}"; shift ;;
    --display-name|--display-name=*)
      # Removed, not ignored: silently accepting it would let an operator
      # believe names were being set. Fail loudly with the reason (exit 2,
      # like any other unknown flag) before touching the cluster.
      echo "--display-name was removed (ADR-0034 D10): deploy-user.sh no longer writes a display name." >&2
      echo "  The initial display name is the user's seat; a participant sets their own name and avatar" >&2
      echo "  in the portal's Me screen. Drop the flag (and any --names-file that fed it)." >&2
      exit 2 ;;
    --flags-file)
      FLAGS_FILE="${2:?--flags-file requires a path}"; shift 2 ;;
    --flags-file=*)
      FLAGS_FILE="${1#--flags-file=}"; shift ;;
    --egress-lockdown)
      EGRESS_LOCKDOWN=1; shift ;;
    --api-server-cidr)
      API_SERVER_CIDR="${2:?--api-server-cidr requires a value}"; shift 2 ;;
    --api-server-cidr=*)
      API_SERVER_CIDR="${1#--api-server-cidr=}"; shift ;;
    -h|--help)
      sed -n '2,50p' "$0"; exit 0 ;;
    --)
      shift; POSITIONAL+=("$@"); break ;;
    -*)
      echo "unknown flag: $1" >&2; exit 2 ;;
    *)
      POSITIONAL+=("$1"); shift ;;
  esac
done
set -- "${POSITIONAL[@]:-}"

USAGE_MSG='usage: deploy-user.sh [--challenges-dir <path>] [--scenarios-dir <path>] <username> <all|NN-slug|scenario:name>'
USERNAME="${1:?${USAGE_MSG}}"
CHALLENGE_ID="${2:?${USAGE_MSG}}"

# The username is the seat: the Helm release name, the `ctf-<seat>` namespace,
# label values and the workspace host's first label (app#480, ADR-0034 D2,
# ADR-0042). It is checked here, before any kubectl / helm call, because
# `--set-string "username=..."` below would read a `,` as the start of another key
# and `=` as another assignment. (--set-string, not --set: --set types a seat such
# as 0, 1e3 or true as a number / boolean, and the chart would then build
# `ctf-1000` for `1e3`; the chart also quotes the label values, which are YAML
# scalars.)
#
# SEAT_PATTERN is a copy of identity.SeatPattern (Go). A test holds the text equal
# (internal/identity/seat_cases_test.go) and scripts/check-seat-grammar.sh runs the
# shared case table (internal/identity/testdata/seat-cases.tsv) through this check.
# C locale so `a-z` is the ASCII range whatever the operator's LANG is; the printed
# value is %q-escaped in the C locale (every byte >= 0x80 becomes an octal escape
# whatever the shell's version or LANG), so a control or bidi character cannot
# reach the terminal raw.
SEAT_PATTERN='^[a-z0-9]([a-z0-9-]{0,51}[a-z0-9])?$'
if ! (export LC_ALL=C; [[ "${USERNAME}" =~ ${SEAT_PATTERN} ]]); then
  (export LC_ALL=C; printf 'invalid username (a seat): %q does not match %s\n' "${USERNAME}" "${SEAT_PATTERN}") >&2
  echo "  (ADR-0034 D2; nothing was deployed)" >&2
  exit 2
fi

# The challenge id is the `--set-string challengeId=` value below and, in the other two
# modes, a path (${CHALLENGES_DIR}/<id>, ${SCENARIOS_DIR}/<name>/scenario.yaml,
# values-scenario-<name>.yaml) and a namespace label value. Until app#494 a single
# id was only tested for existing as a directory, so a `,` or `=` in it reached
# helm's --set parser as another key / assignment, and a `..` walked out of the
# challenges dir. Checked here, before any kubectl / helm call, like the seat.
#
# CHALLENGE_ID_PATTERN is a copy of challengeid.Pattern (Go, ADR-0041); a test
# holds the text equal (internal/catalog/challengeid/shell_cases_test.go).
# SCENARIO_PATTERN has no Go definition: a scenario name is a directory under
# scenarios/ and, as `scenario-<name>`, the value of the falco-ctf/challenge-id
# namespace label, so 1 to 54 characters of [a-z0-9-], the first and the last a
# letter or digit (a label value is at most 63 characters, `scenario-` is 9). A
# test (internal/catalog/scenario_name_test.go) holds the text equal to the table
# header and every real scenarios/<name>/ accepted. scripts/check-deploy-user-ids.sh
# runs both case tables (internal/catalog/challengeid/testdata/challenge-id-cases.tsv,
# internal/catalog/testdata/scenario-name-cases.tsv) through this script.
# `all` is the one fixed word, `scenario:` the one fixed prefix; there is no
# other form (`ALL`, `scenario:` + nothing, `scenario:a:b` are rejected).
CHALLENGE_ID_PATTERN='^[0-9]{2}-[a-z0-9-]{1,60}$'
SCENARIO_PATTERN='^[a-z0-9]([a-z0-9-]{0,52}[a-z0-9])?$'
case "${CHALLENGE_ID}" in
  all) ;;
  scenario:*)
    if ! (export LC_ALL=C; [[ "${CHALLENGE_ID#scenario:}" =~ ${SCENARIO_PATTERN} ]]); then
      (export LC_ALL=C; printf 'invalid scenario name: %q does not match %s\n' "${CHALLENGE_ID#scenario:}" "${SCENARIO_PATTERN}") >&2
      echo "  (app#494; nothing was deployed)" >&2
      exit 2
    fi ;;
  *)
    if ! (export LC_ALL=C; [[ "${CHALLENGE_ID}" =~ ${CHALLENGE_ID_PATTERN} ]]); then
      (export LC_ALL=C; printf 'invalid challenge id: %q does not match %s\n' "${CHALLENGE_ID}" "${CHALLENGE_ID_PATTERN}") >&2
      echo "  (ADR-0041 / app#494; nothing was deployed)" >&2
      exit 2
    fi ;;
esac

# The other operator inputs (app#510, #507 review-5x R1#1): --dns-suffix,
# FALCO_CTF_REGISTRY, FALCO_CTF_IMAGE_TAG and --api-server-cidr. Each is a helm value
# below (a host, an image reference, a NetworkPolicy ipBlock). helm's --set parser reads
# a `,` as the start of another key and `=` as another assignment, and --set-string does
# NOT change that (it only stops the typing: with --set, `null` deletes the key, so a tag
# `null` renders the image `ttyd:` and a dns suffix `null` the host `<seat>.`; measured with
# helm 4.1.3), so the grammar check is what closes the injection and --set-string is what
# closes the typing. Both are needed. The trust boundary is the operator (the caller is
# platform's deploy-event-workspaces.sh), not a participant; this is the same
# closed-grammar rule the seat and the challenge id already follow.
#
# The four patterns have NO Go definition (an operator input is read by this script
# only): these literals are the definitions. A test (internal/catalog,
# deploy_operator_inputs_test.go) holds each equal to the `# pattern: ` header of its
# case table (internal/catalog/testdata/{dns-suffix,image-registry,image-tag,
# api-server-cidr}-cases.tsv) and runs every row through it; scripts/check-deploy-user-ids.sh
# runs every row through this script. Platform derives the registry and the tag from its
# env file (platform#285, open: until it merges the operator passes them) but holds NO
# grammar: this script is the one place that checks. If platform#285 is not merged this
# sentence is to be reverted.
# --app-host and --frame-ancestors (app#520, ADR-0044) are checked below with the same
# helper, and are not part of the four: see "--frame-ancestors / --app-host" after them.
#   DNS_SUFFIX       RFC 1123 subdomain: labels of [a-z0-9-] (the first and the last a letter
#                    or digit, 1 to 63 characters) joined by `.`, no leading / trailing dot,
#                    at most DNS_SUFFIX_MAX_LEN (253) characters in all. Lower case only
#                    (an Ingress host must be). 253 bounds the suffix ALONE: the host
#                    `<seat>.<suffix>` is longer, and whether that fits is judged by helm /
#                    the apiserver, not here.
#   REGISTRY         an OCI `host[:port]/path` ending in `/falco-ctf`: the
#                    `<registry>/<repository prefix>` the three images are appended to. Path components follow the OCI
#                    distribution grammar (`.`, `_`, `__`, `-+` between alphanumerics), so
#                    `..`, `//`, a trailing `/` and any `,` `=` `:` `@` are out. The LAST
#                    component must be `falco-ctf`: the scoreboard ingest drops every event
#                    whose container.image.repository does not contain `falco-ctf/challenge`
#                    (internal/scoreboard/ingest/ingest.go:321-324, which also accepts
#                    `falco-ctf-challenge`; `${REGISTRY}/challenge` can only produce the
#                    first), so a registry without it would deploy a workspace whose
#                    detections are silently never scored. Fail-closed here.
#   IMAGE_TAG        an OCI tag, `[A-Za-z0-9_][A-Za-z0-9._-]{0,127}`.
#   API_SERVER_CIDR  IPv4 `a.b.c.d/n`: each octet 0..255 with no leading zero, n 0..32.
#                    (IPv6 is not accepted: the chart's rule and the stand-up's apiserver
#                    endpoint are IPv4.)
# An empty FALCO_CTF_REGISTRY / FALCO_CTF_IMAGE_TAG means "not set" (the chart default
# is kept), as it always has; an empty --dns-suffix / --api-server-cidr is the usage
# error of the flag parser above. A set value is checked even when the thing it feeds is
# off (--api-server-cidr without --egress-lockdown): a bad value is not ignored quietly.
# C locale, %q-escaped output, like the seat and the id: a control or bidi character
# cannot reach the terminal raw.
DNS_SUFFIX_PATTERN='^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)*$'
DNS_SUFFIX_MAX_LEN='253'
REGISTRY_PATTERN='^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*(:[0-9]{1,5})?(/[a-z0-9]+((\.|_|__|-+)[a-z0-9]+)*)*/falco-ctf$'
IMAGE_TAG_PATTERN='^[A-Za-z0-9_][A-Za-z0-9._-]{0,127}$'
API_SERVER_CIDR_PATTERN='^((25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])\.){3}(25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])/(3[0-2]|[12]?[0-9])$'

# check_operator_input <name> <value> <pattern> [<max length>]: exit 2 on a miss.
check_operator_input() {
  local name="$1" value="$2" pattern="$3" max="${4:-}"
  if ! (export LC_ALL=C; [[ "${value}" =~ ${pattern} ]]); then
    (export LC_ALL=C; printf 'invalid %s: %q does not match %s\n' "${name}" "${value}" "${pattern}") >&2
    echo "  (app#510; nothing was deployed)" >&2
    exit 2
  fi
  # After the pattern, so the value is ASCII and ${#value} counts bytes.
  if [[ -n "${max}" && "${#value}" -gt "${max}" ]]; then
    echo "invalid ${name}: ${#value} characters, at most ${max} allowed" >&2
    echo "  (app#510; nothing was deployed)" >&2
    exit 2
  fi
}
[[ -z "${DNS_SUFFIX}" ]] || check_operator_input "--dns-suffix" "${DNS_SUFFIX}" "${DNS_SUFFIX_PATTERN}" "${DNS_SUFFIX_MAX_LEN}"
[[ -z "${FALCO_CTF_REGISTRY:-}" ]] || check_operator_input "FALCO_CTF_REGISTRY" "${FALCO_CTF_REGISTRY}" "${REGISTRY_PATTERN}"
[[ -z "${FALCO_CTF_IMAGE_TAG:-}" ]] || check_operator_input "FALCO_CTF_IMAGE_TAG" "${FALCO_CTF_IMAGE_TAG}" "${IMAGE_TAG_PATTERN}"
[[ -z "${API_SERVER_CIDR}" ]] || check_operator_input "--api-server-cidr" "${API_SERVER_CIDR}" "${API_SERVER_CIDR_PATTERN}"

# --frame-ancestors / --app-host (app#520, ADR-0044; the cross-repo contract: the value
# comes from platform, the grammar is here and in Go). Both end up in the chart: the first
# as the ttyd-proxy's CSP `frame-ancestors` source (the origins that may frame a root-shell
# terminal), the second as the host of the unauthenticated ttyd Ingress's sign-in redirect
# (auth.authSignin). A `*`, a second source, a `,` (helm reads it as another key) or a path
# would each widen one of them, and --set-string does not stop any of it.
#   APP_HOST         the SAME grammar as --dns-suffix: DNS_SUFFIX_PATTERN and
#                    DNS_SUFFIX_MAX_LEN above (no new literal): a lower case RFC 1123 name, so no
#                    scheme, port, path, userinfo, trailing dot or IPv6.
#   FRAME_ANCESTORS  exactly one source: the quoted keyword 'none', or `https://` and one host
#                    of the APP_HOST grammar, at most FRAME_ANCESTORS_MAX_LEN (`https://` and
#                    253) characters. Not 'self', `*`, `*.`, a scheme alone, `http:`, a port, a
#                    path, several sources, a bare `none`. THE DEFINITION is the Go constant
#                    ttydproxy.FrameAncestorsPattern: this literal is a copy of it, held equal
#                    (with the case table's header and the host part against DNS_SUFFIX_PATTERN)
#                    by internal/ttydproxy/frame_ancestors_grammar_test.go; ttyd-proxy refuses
#                    to start on a value outside it, so a chart used without this script is
#                    closed too. Double quoted, not single: the grammar holds a single quote,
#                    and the test reads the assignment only where bash gives its text back
#                    unchanged.
# The pairing (D3): given both, and the frame-ancestors not 'none', it must be exactly
# https://<app-host>: the one origin that serves the portal is the one that frames ttyd and
# the one the sign-in redirect returns to. Until now only an operator's discipline kept them
# equal. Either alone is checked against its own grammar only. Table rows:
# internal/ttydproxy/testdata/frame-ancestors-cases.tsv and
# internal/catalog/testdata/dns-suffix-cases.tsv (as --app-host), run by
# scripts/check-deploy-user-ids.sh.
FRAME_ANCESTORS_PATTERN="^('none'|https://[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)*)$"
FRAME_ANCESTORS_MAX_LEN='261'
[[ -z "${APP_HOST}" ]] || check_operator_input "--app-host" "${APP_HOST}" "${DNS_SUFFIX_PATTERN}" "${DNS_SUFFIX_MAX_LEN}"
[[ -z "${FRAME_ANCESTORS}" ]] || check_operator_input "--frame-ancestors" "${FRAME_ANCESTORS}" "${FRAME_ANCESTORS_PATTERN}" "${FRAME_ANCESTORS_MAX_LEN}"
if [[ -n "${APP_HOST}" && -n "${FRAME_ANCESTORS}" && "${FRAME_ANCESTORS}" != "'none'" && "${FRAME_ANCESTORS}" != "https://${APP_HOST}" ]]; then
  (export LC_ALL=C; printf 'invalid --frame-ancestors: %q is not https://%q (the --app-host)\n' "${FRAME_ANCESTORS}" "${APP_HOST}") >&2
  echo "  (ADR-0044 D3; nothing was deployed)" >&2
  exit 2
fi

# Egress lockdown (P11.5) requires the apiserver CIDR — without it the chart
# omits the API-server allow and ttyd's `kubectl exec` into the workspace
# breaks. Fail fast here (mirrors platform deploy-event-workspaces.sh), so a
# prod rollout never silently ships a workspace that can't be exec'd into.
if [[ "${EGRESS_LOCKDOWN}" -eq 1 && -z "${API_SERVER_CIDR}" ]]; then
  echo "--egress-lockdown requires --api-server-cidr <cidr>" >&2
  echo "  (the apiserver endpoint CIDR; from terraform output on prod EKS)" >&2
  exit 2
fi

# ADR-WS-0005 enforcement fix (2026-09-01 Bottlerocket PoC): --api-server-cidr
# above authorizes the apiserver's real VPC/ENI address, but in-cluster
# `kubectl` (what ttyd's `kubectl exec` uses) always dials the
# `kubernetes.default` Service ClusterIP instead. Once the cluster's
# NetworkPolicy agent enforces egress, that dial is evaluated against the
# ClusterIP itself — which is OUTSIDE apiServerCidr's range — so `kubectl
# exec` breaks even with a correct --api-server-cidr. Derive the ClusterIP
# ourselves (the `kubernetes` Service in `default` always exists and its
# ClusterIP is exactly what kubelet injects as $KUBERNETES_SERVICE_HOST in
# every Pod on this same cluster) rather than adding a third CLI flag or
# threading a new terraform output through the platform side. Fail fast, same
# rationale as the check above: a silently-empty value would ship a broken
# workspace.
API_SERVER_CLUSTER_IP=""
if [[ "${EGRESS_LOCKDOWN}" -eq 1 ]]; then
  API_SERVER_CLUSTER_IP="$(kubectl get svc kubernetes -n default -o jsonpath='{.spec.clusterIP}' 2>/dev/null || true)"
  if [[ -z "${API_SERVER_CLUSTER_IP}" ]]; then
    echo "--egress-lockdown: could not read the 'kubernetes' Service ClusterIP in the 'default' namespace" >&2
    echo "  (needed so the workspace egress NetworkPolicy allows the API server's" >&2
    echo "   ClusterIP under NetworkPolicy enforcement — ADR-WS-0005 fix; check" >&2
    echo "   kubectl context/access to the target cluster)" >&2
    exit 2
  fi
fi

