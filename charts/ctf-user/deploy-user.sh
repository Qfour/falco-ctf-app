CHALLENGES_DIR="${CHALLENGES_DIR:-${FALCO_CTF_CHALLENGES_DIR:-${DEFAULT_CHALLENGES_DIR}}}"
if [[ ! -d "${CHALLENGES_DIR}" ]]; then
  echo "challenges dir not found: ${CHALLENGES_DIR}" >&2
  echo "  (override with --challenges-dir <path> or FALCO_CTF_CHALLENGES_DIR)" >&2
  exit 1
fi
# Resolve to absolute path so helm -f can find the values overlay if cwd changes.
CHALLENGES_DIR="$(cd "${CHALLENGES_DIR}" && pwd)"

NS="ctf-${USERNAME}"
RELEASE="${USERNAME}"

green()  { printf '\033[32m%s\033[0m\n' "$*"; }
yellow() { printf '\033[33m%s\033[0m\n' "$*"; }
info()   { printf '\033[36m%s\033[0m\n' "$*"; }
red()    { printf '\033[31m%s\033[0m\n' "$*"; }

# Three challenge-id modes (P27-1 added scenario:<name> as the third):
#   all               — every challenge's plant/fixtures (values-all.yaml).
#   scenario:<name>   — ONLY the challenges scenarios/<name>/scenario.yaml
#                        lists (values-scenario-<name>.yaml, GENERATED by
#                        challenges/gen-values.sh).
#   <NN-slug>         — a single challenge (values.yaml if present).
# Fixtures are image-baked at /opt/ctf/missions/<id>/fixtures/** (challenge
# Dockerfile, missions-builder allowlist; ADR-0026 D1) for "all" and
# single-challenge mode — no per-challenge file injection there. Scenario mode
# is the one exception: charts/ctf-user's `missions-scope` initContainer
# (driven by this scope's values file's `scenario.missions` list) prunes
# /opt/ctf/missions/ down to only the scenario's own ids before `challenge`
# starts.
#
# ADR-0026 V4 (fail-closed): after the Pod is up, assert-flag-isolation.sh
# check 3-8 inspects /opt/ctf/missions/ in the running Pod in EVERY mode and
# this script exits non-zero if it is not exactly the expected ids, each
# holding only a plain fixtures/ directory. The expected id set comes from
# --challenges-dir (the operator's checkout), so the checkout and the
# image's ref (FALCO_CTF_IMAGE_TAG) must be the same commit; an image built
# before the allowlist fails here by design (update the image first).
# This is a deploy-moment check only: re-running the assert after participants
# have used the workspace is not evidence about the image (they are root in
# `challenge`). Audit an image with `scripts/check-image-hygiene.sh <digest>`.
ALL_MODE=0
SCENARIO_MODE=0
SCENARIO_NAME=""
case "${CHALLENGE_ID}" in
  all)
    ALL_MODE=1 ;;
  scenario:*)
    SCENARIO_MODE=1
    SCENARIO_NAME="${CHALLENGE_ID#scenario:}"
    ;;
esac

if [[ "${ALL_MODE}" -eq 1 ]]; then
  ALL_VALUES="${CHALLENGES_DIR}/values-all.yaml"
  if [[ ! -f "${ALL_VALUES}" ]]; then
    echo "all-missions mode requires ${ALL_VALUES}" >&2
    exit 1
  fi
  info "using challenges dir: ${CHALLENGES_DIR} (all-missions mode)"
  VALUES_ARGS=(-f "${ALL_VALUES}")
elif [[ "${SCENARIO_MODE}" -eq 1 ]]; then
  # Precedence: --scenarios-dir > default sibling repo (no env override — the
  # platform passthrough this needs is P27-1's own follow-up, see this
  # script's usage comment; unlike --challenges-dir there is no existing
  # FALCO_CTF_* env convention to mirror here yet).
  SCENARIOS_DIR="${SCENARIOS_DIR:-${DEFAULT_SCENARIOS_DIR}}"
  SCENARIO_DIR="${SCENARIOS_DIR}/${SCENARIO_NAME}"
  SCENARIO_FILE="${SCENARIO_DIR}/scenario.yaml"
  if [[ ! -f "${SCENARIO_FILE}" ]]; then
    echo "scenario not found: ${SCENARIO_FILE}" >&2
    echo "  (override with --scenarios-dir <path>; available scenarios:" >&2
    avail=""
    for d in "${SCENARIOS_DIR}"/*/; do
      [[ -f "${d}scenario.yaml" ]] || continue
      avail+="$(basename "${d}") "
    done
    echo "   ${avail})" >&2
    exit 1
  fi
  SCENARIO_VALUES="${CHALLENGES_DIR}/values-scenario-${SCENARIO_NAME}.yaml"
  if [[ ! -f "${SCENARIO_VALUES}" ]]; then
    echo "scenario values not generated: ${SCENARIO_VALUES}" >&2
    echo "  (run 'make gen-values' after adding/editing ${SCENARIO_FILE})" >&2
    exit 1
  fi
  info "using challenges dir: ${CHALLENGES_DIR} (scenario mode: ${SCENARIO_NAME})"
  VALUES_ARGS=(-f "${SCENARIO_VALUES}")
else
  CHALLENGE_DIR="${CHALLENGES_DIR}/${CHALLENGE_ID}"
  CHALLENGE_VALUES="${CHALLENGE_DIR}/values.yaml"

  if [[ ! -d "${CHALLENGE_DIR}" ]]; then
    echo "challenge not found: ${CHALLENGE_DIR}" >&2
    # List challenge sub-directories (each mission is a dir NN-slug); a glob loop
    # avoids parsing `ls` output (SC2010) and copes with odd filenames.
    avail=""
    for d in "${CHALLENGES_DIR}"/*/; do
      [[ -d "${d}" ]] || continue
      avail+="$(basename "${d}") "
    done
    echo "  available: ${avail}all, or scenario:<name>" >&2
    exit 1
  fi

  info "using challenges dir: ${CHALLENGES_DIR}"

  # Optional per-challenge values overlay (e.g. evade challenges' postStart + flag env).
  VALUES_ARGS=()
  if [[ -f "${CHALLENGE_VALUES}" ]]; then
    VALUES_ARGS+=(-f "${CHALLENGE_VALUES}")
  fi
fi

# Real per-event flags (from events/<ev>/flags.dec.yaml, shape `{flags: {id: FALCO{...}}}`).
# Each pair becomes --set-string challenge.flags.<id>=<flag>, overriding the
# chart's FALCO{dev-...} defaults. ADR-0001 Option B: these values render into
# the `ctf-flags` Secret and reach only the `plant` initContainer
# (envFrom/secretKeyRef) — the `challenge` container never sees them (I12).
#
# The file is validated first (validate-flags-file.sh, an early check of the
# rules the scoreboard enforces in internal/catalog): every evade challenge in scope
# for this deploy mode must have a flag; values are restricted to
# FALCO{...} (only A-Za-z0-9_- inside the braces) and may not equal a repository/chart default or
# each other. A rejected file exits here, before anything
# touches the cluster. Only the entries IN SCOPE come back and are passed to
# helm (the rest of the event file never becomes a helm argument). Runs after the mode resolution above because the scope
# (all / scenario / single) decides which ids are required. Without
# --flags-file nothing is validated and the chart defaults are used (local dev).
FLAG_ARGS=()
if [[ -n "${FLAGS_FILE}" ]]; then
  [[ -f "${FLAGS_FILE}" ]] || { echo "flags file not found: ${FLAGS_FILE}" >&2; exit 1; }
  # Explicit status check: the validator's own stderr explains the rejection
  # (challenge ids only, never values).
  if ! FLAG_PAIRS="$("${CHART_DIR}/validate-flags-file.sh" "${FLAGS_FILE}" "${CHALLENGES_DIR}" "${CHALLENGE_ID}" "${SCENARIOS_DIR}")"; then
    echo "flags file validation failed: ${FLAGS_FILE} (see above)" >&2
    exit 1
  fi
  while IFS=$'\t' read -r fid fval; do
    [[ -z "${fid}" ]] && continue
    fkey="$(printf '%s' "${fid}" | sed 's/\./\\./g')"
    FLAG_ARGS+=(--set-string "challenge.flags.${fkey}=${fval}")
  done <<< "${FLAG_PAIRS}"
  # FLAG_ARGS may legitimately be empty here: the validator emits only the
  # entries in scope, and a trigger-only deploy has none.
fi

# Total step count: namespace/rotate/upgrade/verify/assert.
LAST_STEP=5

# Namespace ownership (platform#75 / ADR-0011-consistent single-owner pattern).
#
# platform#75: this call used to invoke `helm upgrade --install` without `-n`
# or `--create-namespace`, so the RELEASE metadata was recorded under helm's
# default namespace (usually `default`) while the rendered resources (every
# template in this chart sets `namespace: {{ include "ctf-user.namespace" . }}`
# explicitly) landed in the real `ctf-<user>` namespace. `helm -n ctf-<user>
# list/uninstall` then found nothing (release: not found) — this is what broke
# teardown silently.
#
# The naive fix ("just add -n \"${NS}\" --create-namespace" to the helm call
# below") is NOT safe on its own: this chart used to template its own
# Namespace object (`templates/namespace.yaml`, now removed). `--create-
# namespace` creates a bare, un-annotated Namespace via the k8s API *before*
# the chart's manifest is applied; if the chart's own Namespace template for
# the *same name* were then applied as part of the very same install, Helm's
# ownership-annotation check would see an already-existing object with no
# `meta.helm.sh/release-name` annotation and refuse it ("invalid ownership
# metadata"). That is exactly the two-owners conflict ADR-0011
# (docs/adr/0011-namespace-bootstrap-single-owner.md) fixed for auth-policy/
# collector/scoreboard/docs, and ADR-0011 explicitly requires that any fix to
# this script decide the ctf-user namespace ownership question rather than
# reintroducing the same conflict (see that ADR's Context/Consequences:
# "platform#75 対応時の条件").
#
# ADR-0011's own pattern doesn't fit here as-is: its bootstrap `namespaces`
# chart only `range`s a static list resolved at helmfile render time, but
# ctf-user namespaces are created dynamically per participant outside
# helmfile's management. So this script — the one and only thing that ever
# creates a `ctf-<user>` namespace — takes on the single-owner role directly:
# it creates/labels the Namespace itself with plain `kubectl` (idempotent, no
# Helm involvement) *before* invoking Helm, and the chart no longer templates
# a Namespace object at all. `helm upgrade --install` below then only ever
# sees a namespace that already exists with the right labels, so its
# `--create-namespace` flag is a harmless no-op safety net (it only fires if
# this pre-step were ever skipped by calling helm directly), not the
# mechanism relied on.
#
# Stray releases from before this fix: past `deploy-user.sh` runs (pre-fix)
# recorded their release metadata under the default namespace. This is not a
# hypothetical — it is confirmed to exist right now on the local colima
# cluster (`helm -n default list` shows user1..user5 recorded there, all
# pre-fix). Do not assume a given cluster is clean; check before assuming
# `helm upgrade --install -n "${NS}"` below will behave like a normal
# first-time install for this user. The detection step immediately below
# checks `helm -n default status "${RELEASE}"` and fails loudly (exit 1) if a
# stray pre-fix release is found, rather than silently colliding with it or
# uninstalling it automatically.
# platform#75 stray-release detection (fail-loud, no automatic uninstall —
# this script never runs a destructive `helm uninstall` on its own). Runs
# before the namespace/pod steps below, not just before the `helm upgrade
# --install` call: this is confirmed to actually exist on clusters today (not
# a hypothetical — see the comment above), so it's cheaper to fail here than
# to first touch the namespace/pod and only then discover `helm upgrade -n
# "${NS}"` would collide with release metadata still recorded under
# `default` from a pre-fix run.
if helm -n default status "${RELEASE}" >/dev/null 2>&1; then
  red "  ✗ stray pre-fix release '${RELEASE}' found in namespace 'default'"
  red "    (platform#75: this release predates the -n/--create-namespace fix)"
  red "    fix: helm -n default uninstall ${RELEASE}   # then re-run this script"
  exit 1
fi

info "[1/${LAST_STEP}] ensure namespace ${NS} (single owner: this script)"
kubectl create namespace "${NS}" --dry-run=client -o yaml | kubectl apply -f - >/dev/null
# k8s label VALUES may not contain ':' — CHALLENGE_ID is "scenario:<name>" in
# scenario mode, so sanitize just for this label (the raw value with its
# colon is still what's passed to helm --set challengeId=... below, and to
# assert-flag-isolation.sh, unchanged).
NS_CHALLENGE_LABEL="${CHALLENGE_ID//:/-}"
kubectl label namespace "${NS}" --overwrite \
  app.kubernetes.io/name=ctf-user \
  app.kubernetes.io/instance="${USERNAME}" \
  app.kubernetes.io/managed-by=deploy-user.sh \
  app.kubernetes.io/part-of=falco-ctf \
  falco-ctf/username="${USERNAME}" \
  falco-ctf/challenge-id="${NS_CHALLENGE_LABEL}" \
  pod-security.kubernetes.io/enforce=baseline \
  pod-security.kubernetes.io/audit=restricted \
  pod-security.kubernetes.io/warn=restricted >/dev/null

info "[2/${LAST_STEP}] rotate workspace Pod (Pod fields are immutable across helm upgrade)"
# `--ignore-not-found` makes this safe for first-time installs.
# Errors here would only mean the namespace doesn't exist yet, also fine.
kubectl -n "${NS}" delete pod workspace --ignore-not-found --wait=true >/dev/null 2>&1 || true

# Prod image override (chart default is docker.io/falco-ctf/*:dev for local). Set
#   FALCO_CTF_REGISTRY  = <acct>.dkr.ecr.<region>.amazonaws.com/falco-ctf
#   FALCO_CTF_IMAGE_TAG = <git SHA>
# to pull ttyd/ttyd-proxy/challenge from ECR (I5: same SHA tag across all
# images). The challenge repo must keep the `falco-ctf/challenge` substring
# (scoreboard ingest filter).
# --set-string, not --set (app#510): `null` is a valid OCI tag and a valid DNS label,
# and --set would read it as "delete the key" (an empty tag); the values were
# grammar-checked above, so a `,` or `=` is not in them either.
IMAGE_ARGS=()
if [[ -n "${FALCO_CTF_REGISTRY:-}" ]]; then
  IMAGE_ARGS+=(--set-string "ttyd.image.repository=${FALCO_CTF_REGISTRY}/ttyd")
  IMAGE_ARGS+=(--set-string "ttyd.proxy.image.repository=${FALCO_CTF_REGISTRY}/ttyd-proxy")
  IMAGE_ARGS+=(--set-string "challenge.image.repository=${FALCO_CTF_REGISTRY}/challenge")
fi
if [[ -n "${FALCO_CTF_IMAGE_TAG:-}" ]]; then
  IMAGE_ARGS+=(--set-string "ttyd.image.tag=${FALCO_CTF_IMAGE_TAG}")
  IMAGE_ARGS+=(--set-string "ttyd.proxy.image.tag=${FALCO_CTF_IMAGE_TAG}")
  IMAGE_ARGS+=(--set-string "challenge.image.tag=${FALCO_CTF_IMAGE_TAG}")
fi

# --dns-suffix: the workspace host is `<seat>.<dnsSuffix>`. Same --set-string rationale
# as IMAGE_ARGS above, and the same array form as the ones below.
DNS_SUFFIX_ARGS=()
if [[ -n "${DNS_SUFFIX}" ]]; then
  DNS_SUFFIX_ARGS+=(--set-string "dnsSuffix=${DNS_SUFFIX}")
fi

# P23-3: CSP frame-ancestors for the ttyd-proxy sidecar. Omit to keep the
