// Package catalogtest writes the scenario fixtures of tests: a scenarios/<id>/ directory in
// the form catalog.LoadScenario accepts since ADR-0055 S2c (a module.yaml, and the
// scenario.yaml cmd/gen-scenarios writes from it, whose id is the directory's name). It is the
// one helper for that, shared by the tests of internal/catalog, internal/edition (through
// editiontest) and cmd/scoreboard, so a fixture cannot drift from what the loader requires
// one copy at a time.
//
// It imports nothing of the module (internal/catalog's own tests import it), so the names of
// the two files are spelled here; catalog's tests load what it writes, which is what holds
// them to catalog.ModuleFile and catalog.ScenarioFile. Every value is a placeholder.
//
// Since S3a a scenario.yaml has a requirements block (D6) that catalog.LoadScored compares
// with what the scope's catalog derives. This package cannot derive it (it does not import
// catalog), so the block is given (Requirements): a test that loads the scenario through
// LoadScored gives the derived value (internal/catalog's WriteScenarioFor, editiontest's
// PutScenario), and Scenario / WriteScenario write the zero block.
package catalogtest

import (
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

// Requirements is the requirements block (ADR-0055 D6) of a fixture scenario, in plain values:
// what catalog.DeriveRequirements gives for the scope's challenges (sorted lists, nothing
// twice). The zero value is the block of a scope with no rule, no exfil, no detect and no
// investigate challenge. The values are written plain, so a fixture uses names that YAML
// reads plain as themselves (the generator quotes the others; TestRender_IsTheFixtureHelpersScenario
// holds the two to the same bytes).
type Requirements struct {
	Answers       []string
	Detect, Exfil bool
	Rules         []string
}

// text is the block as cmd/gen-scenarios writes it: the four keys in order, an empty list as
// "[]", a list as one "    - <value>" line per value.
func (r Requirements) text() string {
	var b strings.Builder
	b.WriteString("requirements:\n")
	list := func(key string, items []string) {
		if len(items) == 0 {
			b.WriteString("  " + key + ": []\n")
			return
		}
		b.WriteString("  " + key + ":\n")
		for _, it := range items {
			b.WriteString("    - " + it + "\n")
		}
	}
	list("answers", r.Answers)
	b.WriteString("  detect: " + strconv.FormatBool(r.Detect) + "\n")
	b.WriteString("  exfil: " + strconv.FormatBool(r.Exfil) + "\n")
	list("rules", r.Rules)
	return b.String()
}

// Module is the module.yaml of the module id (ADR-0055 D3), version 1, whose missions are
// missions, in that order: one or more ids, none twice (the module is invalid otherwise).
func Module(id string, missions ...string) string {
	return "id: " + id + "\ntitle: Title " + id + "\nsummary: A placeholder module of a test.\n" +
		"outcomes: [a, b, c]\nversion: 1\nlevel: 1\nduration: {handsOnMinutes: 10, debriefMinutes: 5}\n" +
		"missions:\n  - " + strings.Join(missions, "\n  - ") + "\n"
}

// Scenario is ScenarioWith(id, Requirements{}, challenges...): the zero requirements block.
func Scenario(id string, challenges ...string) string {
	return ScenarioWith(id, Requirements{}, challenges...)
}

// ScenarioWith is the scenario.yaml cmd/gen-scenarios writes for Module(id, challenges...)
// alone (D5, source kind module) over a scope whose requirements are req: the header, id,
// title, the block list challenges, source and requirements.
func ScenarioWith(id string, req Requirements, challenges ...string) string {
	return "# GENERATED by gen-scenarios from scenarios/" + id + "/module.yaml — DO NOT EDIT\n" +
		"# Edit the source, not this file, then run make gen-scenarios.\n" +
		"id: " + id + "\ntitle: Title " + id + "\nchallenges:\n  - " + strings.Join(challenges, "\n  - ") + "\n" +
		"source:\n  kind: module\n  modules:\n    - id: " + id + "\n      version: 1\n" +
		req.text()
}

// WriteScenario is WriteScenarioWith(t, root, id, Requirements{}, challenges...): for a test
// that does not load the scenario through catalog.LoadScored, or whose scope requires nothing.
func WriteScenario(t testing.TB, root, id string, challenges ...string) string {
	t.Helper()
	return WriteScenarioWith(t, root, id, Requirements{}, challenges...)
}

// WriteScenarioWith writes <root>/<id>/module.yaml, then <root>/<id>/scenario.yaml
// (ScenarioWith), of the challenges in that order (replacing the files when they are there),
// and returns the path of the scenario.yaml. root is a directory the test owns (t.TempDir()),
// never scenarios/.
func WriteScenarioWith(t testing.TB, root, id string, req Requirements, challenges ...string) string {
	t.Helper()
	dir := filepath.Join(root, id)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	for _, f := range [][2]string{{"module.yaml", Module(id, challenges...)}, {"scenario.yaml", ScenarioWith(id, req, challenges...)}} {
		if err := os.WriteFile(filepath.Join(dir, f[0]), []byte(f[1]), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return filepath.Join(dir, "scenario.yaml")
}
