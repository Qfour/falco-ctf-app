// Package catalogtest writes the scenario fixtures of tests: a scenarios/<id>/ directory in
// the form catalog.LoadScenario accepts since ADR-0055 S2c (a module.yaml, and the
// scenario.yaml cmd/gen-scenarios writes from it, whose id is the directory's name). It is the
// one helper for that, shared by the tests of internal/catalog, internal/edition (through
// editiontest) and cmd/scoreboard, so a fixture cannot drift from what the loader requires
// one copy at a time.
//
// It imports nothing of the module (internal/catalog's own tests import it), so the names of
// the two files are spelled here; catalog's tests load what it writes, which is what holds
// them to catalog.ModuleFile and catalog.ScenarioFile. Every value is a placeholder.
package catalogtest

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// Module is the module.yaml of the module id (ADR-0055 D3), version 1, whose missions are
// missions, in that order: one or more ids, none twice (the module is invalid otherwise).
func Module(id string, missions ...string) string {
	return "id: " + id + "\ntitle: Title " + id + "\nsummary: A placeholder module of a test.\n" +
		"outcomes: [a, b, c]\nversion: 1\nlevel: 1\nduration: {handsOnMinutes: 10, debriefMinutes: 5}\n" +
		"missions:\n  - " + strings.Join(missions, "\n  - ") + "\n"
}

// Scenario is the scenario.yaml cmd/gen-scenarios writes for Module(id, challenges...)
// alone (D5, source kind module): the header, id, title, the block list challenges and
// source.
func Scenario(id string, challenges ...string) string {
	return "# GENERATED by gen-scenarios from scenarios/" + id + "/module.yaml — DO NOT EDIT\n" +
		"# Edit the source, not this file, then run make gen-scenarios.\n" +
		"id: " + id + "\ntitle: Title " + id + "\nchallenges:\n  - " + strings.Join(challenges, "\n  - ") + "\n" +
		"source:\n  kind: module\n  modules:\n    - id: " + id + "\n      version: 1\n"
}

// WriteScenario writes <root>/<id>/module.yaml, then <root>/<id>/scenario.yaml, of the
// challenges in that order (replacing the files when they are there), and returns the path
// of the scenario.yaml. root is a directory the test owns (t.TempDir()), never scenarios/.
func WriteScenario(t testing.TB, root, id string, challenges ...string) string {
	t.Helper()
	dir := filepath.Join(root, id)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	for _, f := range [][2]string{{"module.yaml", Module(id, challenges...)}, {"scenario.yaml", Scenario(id, challenges...)}} {
		if err := os.WriteFile(filepath.Join(dir, f[0]), []byte(f[1]), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return filepath.Join(dir, "scenario.yaml")
}
