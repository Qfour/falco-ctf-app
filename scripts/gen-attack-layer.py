#!/usr/bin/env python3
"""Generate the MITRE ATT&CK Navigator layer + coverage table from challenges/.

  python3 scripts/gen-attack-layer.py [repo-root]     # default: repo root (../ of scripts/)

Single source of truth: the `attack:` block in each
challenges/<NN>-<slug>/falco-rule.yaml (tactic / techniqueId / techniqueName).
catalog.go ignores that block (yaml.v3, non-strict), so it lives with the
challenge it describes and cannot drift from the mission definition.

Global outputs (both committed, both GENERATED — do not hand-edit, and both
UNCHANGED by the scenario support below — they aggregate every challenge under
challenges/ regardless of scenario membership):
  challenges/attack-navigator-layer.json  — ATT&CK Navigator layer format v4.5
  challenges/ATTACK-COVERAGE.md            — tactic-by-tactic coverage table

Per-scenario output (P27-3, additive, GENERATED — do not hand-edit), one per
scenarios/<name>/scenario.yaml found:
  scenarios/<name>/attack-coverage.md      — same table, scoped to that
                                              scenario's `challenges:` list

scenario.yaml may optionally declare a `tactics:` list (advisory — Go's
catalog.go ignores it, non-strict yaml.v3). When present, this script compares
it against the tactics actually exercised by the scenario's challenges and
prints a non-blocking warning (stdout, exit code unchanged) on any mismatch.

The run is idempotent: running twice produces a zero diff. Regenerate with
`make gen-attack` after changing any attack: block or any scenario.yaml.
"""
