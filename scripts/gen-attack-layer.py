def _yaml_scalar(ln, key):
    """Return the stripped/unquoted scalar value of a `key: value` line, or None."""
    m = re.match(rf"^{re.escape(key)}:\s*(.+?)\s*$", ln)
    if not m:
        return None
    return m.group(1).strip().strip('"').strip("'")


def _yaml_list_item(ln):
    """Return the value of a `  - item  # comment` list line, or None if not a list line."""
    stripped = ln.strip()
    if not stripped.startswith("-"):
        return None
    rest = stripped[1:].strip()
    if rest.startswith('"'):
        end = rest.find('"', 1)
        return rest[1:end] if end != -1 else rest.strip('"')
    if rest.startswith("'"):
        end = rest.find("'", 1)
        return rest[1:end] if end != -1 else rest.strip("'")
    hash_idx = rest.find("#")
    if hash_idx != -1:
        rest = rest[:hash_idx]
    return rest.strip()


def _yaml_block_list(lines, key):
    """Return the items of a top-level `key:` block-style YAML list, or []."""
    items = []
    in_block = False
    for ln in lines:
        if re.match(rf"^{re.escape(key)}:\s*$", ln):
            in_block = True
            continue
        if not in_block:
            continue
        if not ln.strip():
            continue
        if ln.strip().startswith("-"):
            item = _yaml_list_item(ln)
            if item:
                items.append(item)
            continue
        break  # dedented out of the block (next top-level key)
    return items


def load_scenarios(root):
    """Return [{dir, id, title, challenges, tactics_declared}] for each
    scenarios/<name>/scenario.yaml. `tactics_declared` is [] when the
    optional `tactics:` field is absent."""
    scen_root = os.path.join(root, "scenarios")
    if not os.path.isdir(scen_root):
        return []
    scenarios = []
    for name in sorted(os.listdir(scen_root)):
        spath = os.path.join(scen_root, name, "scenario.yaml")
        if not os.path.isfile(spath):
            continue
        with open(spath, encoding="utf-8") as f:
            lines = f.read().splitlines()
        sid, title = name, name
        for ln in lines:
            v = _yaml_scalar(ln, "id")
            if v is not None:
                sid = v
            v = _yaml_scalar(ln, "title")
            if v is not None:
                title = v
        scenarios.append({
            "dir": name,
            "id": sid,
            "title": title,
            "challenges": _yaml_block_list(lines, "challenges"),
            "tactics_declared": _yaml_block_list(lines, "tactics"),
        })
    return scenarios


def build_scenario_coverage_md(scenario, selected_missions):
    """Same table shape as build_coverage_md(), scoped to one scenario."""
    lines = []
    lines.append("<!-- GENERATED by scripts/gen-attack-layer.py — DO NOT EDIT. -->")
    lines.append("<!-- Source: scenarios/{}/scenario.yaml `challenges:` + "
                 "challenges/*/falco-rule.yaml `attack:` blocks. "
                 "Regenerate: make gen-attack. -->".format(scenario["dir"]))
    lines.append("")
    lines.append(f"# ATT&CK カバレッジ — {scenario['title']} (`{scenario['id']}`)")
    lines.append("")
    lines.append(f"このシナリオが含む {len(selected_missions)} 課題の Tactic / Technique 対応表 "
                 "(scenario.yaml の `challenges:` 順)。全課題のグローバルカバレッジは "
                 "`challenges/ATTACK-COVERAGE.md` を参照。")
    lines.append("")
    lines.append("## カバーする Tactic / Technique")
    lines.append("")
    lines.append("| # | Mission | Tactic | Technique | Technique 名 |")
    lines.append("|---|---|---|---|---|")
    for m in selected_missions:
        lines.append(
            f"| {m['slug'][:2]} | {m['title']} | {m['tactic']} | "
            f"`{m['techniqueId']}` | {m['techniqueName']} |"
        )
    lines.append("")

    declared = scenario["tactics_declared"]
    if declared:
        # First-occurrence order over selected_missions, de-duplicated.
        actual_ordered = []
        seen = set()
        for m in selected_missions:
            if m["tactic"] not in seen:
                seen.add(m["tactic"])
                actual_ordered.append(m["tactic"])
        lines.append("## 宣言 tactics (scenario.yaml) との一致")
        lines.append("")
        lines.append(f"宣言: {', '.join(declared)}")
        lines.append("")
        lines.append(f"実際: {', '.join(actual_ordered)}")
        lines.append("")
        if set(declared) == set(actual_ordered):
            lines.append("一致 (advisory チェック済み — 詳細は `make gen-attack` の標準出力)。")
        else:
            lines.append("**不一致あり** — 詳細は `make gen-attack` 実行時の標準出力 warning を参照。")
        lines.append("")
    return "\n".join(lines)


def warn_tactic_mismatch(scenario, selected_missions):
    """Advisory only: print (not fail) if declared tactics: drifts from the
    tactics actually exercised by the scenario's challenges. Non-blocking —
    never changes the process exit code."""
    declared = scenario["tactics_declared"]
    if not declared:
        return
    declared_set = set(declared)
    actual_set = {m["tactic"] for m in selected_missions}
    missing = sorted(declared_set - actual_set)
    undeclared = sorted(actual_set - declared_set)
    if missing:
        print(f"warning: scenarios/{scenario['dir']}/scenario.yaml declares tactics: "
              f"with no covering challenge: {missing}")
    if undeclared:
        print(f"warning: scenarios/{scenario['dir']}/scenario.yaml's challenges cover "
              f"tactics not declared in tactics:: {undeclared}")


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else \
        os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    missions = load_missions(root)

    layer = build_layer(missions)
    layer_path = os.path.join(root, "challenges", "attack-navigator-layer.json")
    with open(layer_path, "w", encoding="utf-8") as f:
        json.dump(layer, f, ensure_ascii=False, indent=2, sort_keys=False)
        f.write("\n")
    print(f"wrote {os.path.relpath(layer_path, root)} "
          f"({len(layer['techniques'])} techniques, {len(missions)} missions)")

    cov_path = os.path.join(root, "challenges", "ATTACK-COVERAGE.md")
    with open(cov_path, "w", encoding="utf-8") as f:
        f.write(build_coverage_md(missions))
    print(f"wrote {os.path.relpath(cov_path, root)}")

    # --- per-scenario coverage (P27-3, additive) -----------------------------
    # By the time we're here, load_missions() above already fail-closed on any
    # challenges/NN-* dir missing a complete attack: block, so every id a
    # scenario.yaml can legally reference is guaranteed present in by_slug.
    by_slug = {m["slug"]: m for m in missions}
    for scenario in load_scenarios(root):
        selected = []
        for cid in scenario["challenges"]:
            m = by_slug.get(cid)
            if m is None:
                sys.exit(f"error: scenarios/{scenario['dir']}/scenario.yaml "
                         f"references unknown challenge id '{cid}'")
            selected.append(m)

        scen_cov_path = os.path.join(root, "scenarios", scenario["dir"], "attack-coverage.md")
        with open(scen_cov_path, "w", encoding="utf-8") as f:
            f.write(build_scenario_coverage_md(scenario, selected))
        print(f"wrote {os.path.relpath(scen_cov_path, root)} ({len(selected)} challenges)")

        warn_tactic_mismatch(scenario, selected)


if __name__ == "__main__":
    main()
