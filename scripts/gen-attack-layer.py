#!/usr/bin/env python3
"""Generate the MITRE ATT&CK Navigator layer + coverage table from challenges/.

  python3 scripts/gen-attack-layer.py [repo-root]     # default: repo root (../ of scripts/)

Single source of truth: the `attack:` block in each
challenges/<NN>-<slug>/falco-rule.yaml (tactic / techniqueId / techniqueName).
catalog.go ignores that block (yaml.v3, non-strict), so it lives with the
challenge it describes and cannot drift from the mission definition.

Outputs (both committed, both GENERATED — do not hand-edit):
  challenges/attack-navigator-layer.json  — ATT&CK Navigator layer format v4.5
  challenges/ATTACK-COVERAGE.md            — tactic-by-tactic coverage table

The run is idempotent: running twice produces a zero diff. Regenerate with
`make gen-attack` after changing any attack: block.
"""
import json
import os
import re
import sys

# --- config -----------------------------------------------------------------
# ATT&CK Enterprise version the mappings were authored against. Bump together
# with any technique-id review. navigatorVersion tracks the layer schema.
ATTACK_VERSION = "15"
NAVIGATOR_VERSION = "4.9.5"
LAYER_VERSION = "4.5"
DOMAIN = "enterprise-attack"

COVERED_COLOR = "#e60d0d"   # Navigator red — techniques a mission exercises
COVERED_SCORE = 100

# Gaps we intentionally leave uncovered, surfaced in the coverage doc so the
# story's scope is explicit rather than accidental.
INTENTIONAL_GAPS = [
    ("Lateral Movement", "T1021 系 (Remote Services)",
     "未カバー — 単一 Pod 侵入シナリオのため横展開は物語の範囲外。"),
    ("Impact", "T1485 / T1486 系 (Data Destruction / Encryption)",
     "意図的除外 — 破壊的操作は共有 CTF 環境の保護のため扱わない。"),
]

GENERATED_NOTE_JSON = (
    "GENERATED by scripts/gen-attack-layer.py — DO NOT EDIT. "
    "Source: challenges/*/falco-rule.yaml `attack:` blocks. Regenerate: make gen-attack."
)


# --- minimal YAML read (no PyYAML dependency) --------------------------------
# We only need the flat `attack:` block; parse it directly so the generator has
# no third-party deps (matches gen-pages.py, which is stdlib-only).
def read_attack(path):
    """Return {tactic, techniqueId, techniqueName} from a falco-rule.yaml, or None."""
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()
    in_block = False
    out = {}
    for ln in lines:
        if re.match(r"^attack:\s*$", ln):
            in_block = True
            continue
        if in_block:
            m = re.match(r"^  (\w+):\s*(.+?)\s*$", ln)
            if m:
                out[m.group(1)] = m.group(2).strip().strip('"').strip("'")
            elif ln.strip() and not ln.startswith("  "):
                break  # dedented out of the block
    if {"tactic", "techniqueId", "techniqueName"} <= out.keys():
        return out
    return None


def mission_title(cdir):
    readme = os.path.join(cdir, "README.md")
    title = os.path.basename(cdir)
    if os.path.isfile(readme):
        first = open(readme, encoding="utf-8").readline().lstrip("# ").strip()
        if first:
            title = first
    # Drop a leading "NN — " / "NN - " prefix; the table has its own # column
    # and the Navigator comment already carries the slug.
    return re.sub(r"^\d\d\s*[—-]\s*", "", title)


def load_missions(root):
    cdir_root = os.path.join(root, "challenges")
    names = sorted(
        d for d in os.listdir(cdir_root)
        if re.match(r"^\d\d-", d) and os.path.isdir(os.path.join(cdir_root, d))
    )
    missions = []
    for nn in names:
        cdir = os.path.join(cdir_root, nn)
        attack = read_attack(os.path.join(cdir, "falco-rule.yaml"))
        if attack is None:
            sys.exit(f"error: {nn}/falco-rule.yaml has no complete attack: block")
        missions.append({
            "slug": nn,
            "title": mission_title(cdir),
            "tactic": attack["tactic"],
            "techniqueId": attack["techniqueId"],
            "techniqueName": attack["techniqueName"],
        })
    if not missions:
        sys.exit("error: no missions found under challenges/")
    return missions


# --- Navigator layer ---------------------------------------------------------
def build_layer(missions):
    # Group missions by technique id so a technique hit by >1 mission gets one
    # entry with a combined comment (deterministic order = mission order).
    by_tech = {}
    order = []
    for m in missions:
        tid = m["techniqueId"]
        if tid not in by_tech:
            by_tech[tid] = []
            order.append(tid)
        by_tech[tid].append(m)

    techniques = []
    for tid in order:
        ms = by_tech[tid]
        comment = "; ".join(f"{m['slug']} {m['title']} — {m['techniqueName']}" for m in ms)
        techniques.append({
            "techniqueID": tid,
            "score": COVERED_SCORE,
            "color": COVERED_COLOR,
            "comment": comment,
            "enabled": True,
        })

    return {
        "name": "Falco CTF — CTF Company killchain",
        "description": GENERATED_NOTE_JSON,
        "versions": {
            "attack": ATTACK_VERSION,
            "navigator": NAVIGATOR_VERSION,
            "layer": LAYER_VERSION,
        },
        "domain": DOMAIN,
        "techniques": techniques,
        "gradient": {
            "colors": ["#ffffff", COVERED_COLOR],
            "minValue": 0,
            "maxValue": 100,
        },
        "legendItems": [
            {"label": "CTF ミッションでカバー", "color": COVERED_COLOR},
        ],
        "sorting": 0,
        "hideDisabled": False,
    }


# --- coverage markdown -------------------------------------------------------
def build_coverage_md(missions):
    lines = []
    lines.append("<!-- GENERATED by scripts/gen-attack-layer.py — DO NOT EDIT. -->")
    lines.append("<!-- Source: challenges/*/falco-rule.yaml `attack:` blocks. "
                 "Regenerate: make gen-attack. -->")
    lines.append("")
    lines.append("# ATT&CK カバレッジ — CTF Company killchain")
    lines.append("")
    lines.append(f"MITRE ATT&CK Enterprise (v{ATTACK_VERSION}) 対応表。"
                 "Navigator レイヤは `attack-navigator-layer.json`。")
    lines.append("")
    lines.append("## カバーする Tactic / Technique")
    lines.append("")
    lines.append("| # | Mission | Tactic | Technique | Technique 名 |")
    lines.append("|---|---|---|---|---|")
    for m in missions:
        lines.append(
            f"| {m['slug'][:2]} | {m['title']} | {m['tactic']} | "
            f"`{m['techniqueId']}` | {m['techniqueName']} |"
        )
    lines.append("")
    lines.append("## 意図的に扱わない領域 (カバレッジの穴)")
    lines.append("")
    lines.append("| Tactic | Technique | 理由 |")
    lines.append("|---|---|---|")
    for tactic, tech, reason in INTENTIONAL_GAPS:
        lines.append(f"| {tactic} | {tech} | {reason} |")
    lines.append("")
    return "\n".join(lines)


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else \
        os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    missions = load_missions(root)

    layer = build_layer(missions)
    layer_path = os.path.join(root, "challenges", "attack-navigator-layer.json")
    with open(layer_path, "w", encoding="utf-8") as f:
        json.dump(layer, f, ensure_ascii=False, indent=2, sort_keys=False)
        f.write("\n")
    print(f"wrote {os.path.relpath(layer_path, root)} "
          f"({len(layer['techniques'])} techniques, {len(missions)} missions)")

    cov_path = os.path.join(root, "challenges", "ATTACK-COVERAGE.md")
    with open(cov_path, "w", encoding="utf-8") as f:
        f.write(build_coverage_md(missions))
    print(f"wrote {os.path.relpath(cov_path, root)}")


if __name__ == "__main__":
    main()
