// goldenCourse is the whole scenario.yaml the fixture's course generates. Its title needs
// quoting (": "); the shared 02-b stays at its first place.
const goldenCourse = `# GENERATED by gen-scenarios from scenarios/course-x/course.yaml — DO NOT EDIT
# Edit the source, not this file, then run make gen-scenarios.
id: course-x
title: "Course X: two modules"
challenges:
  - 01-a
  - 02-b
  - 03-c
source:
  kind: course
  modules:
    - id: mod-a
      version: 1
      edition: 2h
    - id: mod-b
      version: 2
`

const legacyScenario = "id: legacy\ntitle: Legacy\nchallenges:\n  - 01-a # hand-written\n"

func moduleYAML(id string, version string, missions ...string) string {
	return "id: " + id + "\ntitle: Title " + id + "\nsummary: s\noutcomes: [a, b, c]\nversion: " + version +
		"\nlevel: 1\nduration: {handsOnMinutes: 10, debriefMinutes: 5}\n" +
		"editions:\n  2h: {handsOnMinutes: 60, debriefMinutes: 10, playbook: playbook-2h.md}\n" +
		"missions:\n  - " + strings.Join(missions, "\n  - ") + "\n"
}

const courseYAML = "id: course-x\ntitle: \"Course X: two modules\"\ntimebox: {minutes: 120}\n" +
	"modules:\n  - id: mod-a\n    edition: 2h\n  - id: mod-b\nshared: [02-b]\n"

func put(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, root, rel string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// newTree is a pool of three trigger challenges, two modules, a course over both, a
// directory with no source (a hand-written scenario.yaml) and a README.
func newTree(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	for _, id := range []string{"01-a", "02-b", "03-c"} {
		put(t, root, "challenges/"+id+"/falco-rule.yaml", "type: trigger\nexpectedRules: [Rule "+id+"]\n")
	}
	put(t, root, "scenarios/mod-a/module.yaml", moduleYAML("mod-a", "1", "01-a", "02-b"))
	put(t, root, "scenarios/mod-b/module.yaml", moduleYAML("mod-b", "2", "03-c", "02-b"))
	put(t, root, "scenarios/course-x/course.yaml", courseYAML)
	put(t, root, "scenarios/legacy/scenario.yaml", legacyScenario)
	put(t, root, "scenarios/README.md", "readme\n")
	return root
}

func gen(t *testing.T, args ...string) (int, string, string) {
	t.Helper()
	var out, errb bytes.Buffer
	code := run(args, &out, &errb)
	return code, out.String(), errb.String()
}

func TestGenerate_GoldenAndUntouched(t *testing.T) {
	root := newTree(t)
	if code, _, stderr := gen(t, root); code != exitOK {
		t.Fatalf("exit %d: %s", code, stderr)
	}
	if got := read(t, root, "scenarios/course-x/scenario.yaml"); got != goldenCourse {
		t.Fatalf("course scenario.yaml =\n%s\nwant\n%s", got, goldenCourse)
	}
	if got := read(t, root, "scenarios/mod-b/scenario.yaml"); !strings.Contains(got, "challenges:\n  - 03-c\n  - 02-b\nsource:\n  kind: module\n") {
		t.Fatalf("solo course of mod-b =\n%s", got)
	}
	if got := read(t, root, "scenarios/legacy/scenario.yaml"); got != legacyScenario {
		t.Fatalf("a directory without a source was rewritten:\n%s", got)
	}
	if got := read(t, root, "scenarios/README.md"); got != "readme\n" {
		t.Fatalf("scenarios/README.md was rewritten: %q", got)
	}
}

// The same input gives the same bytes, run after run (map order is random per range).
func TestGenerate_Deterministic(t *testing.T) {
	root := newTree(t)
	var first []genFile
	for i := 0; i < 20; i++ {
		files, _, err := generate(root)
		if err != nil {
			t.Fatal(err)
		}
		if i == 0 {
			first = files
			continue
		}
		if !slices.EqualFunc(files, first, func(a, b genFile) bool { return a.rel == b.rel && bytes.Equal(a.data, b.data) }) {
			t.Fatalf("run %d differs from run 0", i)
		}
	}
	if len(first) != 3 {
		t.Fatalf("generated %d files, want 3 (course-x, mod-a, mod-b)", len(first))
	}
}

// V5: --check is red on a copy of the generated file with one byte changed, and names it;
// the untouched tree is green first and again after the byte is put back.
func TestCheck_OneByteEditIsRed(t *testing.T) {
	const rel = "scenarios/course-x/scenario.yaml"
	edits := []struct {
		name string
		edit func(string) string
	}{
		{"a challenge id", func(s string) string { return strings.Replace(s, "  - 02-b\n", "  - 02-c\n", 1) }},
		{"a byte appended", func(s string) string { return s + " " }},
		{"the last newline removed", func(s string) string { return strings.TrimSuffix(s, "\n") }},
		{"the header", func(s string) string { return strings.Replace(s, "# GENERATED", "# gENERATED", 1) }},
		{"LF to CRLF on one line", func(s string) string { return strings.Replace(s, "challenges:\n", "challenges:\r\n", 1) }},
	}
	root := newTree(t)
	if code, _, stderr := gen(t, root); code != exitOK {
		t.Fatalf("generate: exit %d: %s", code, stderr)
	}
	good := read(t, root, rel)
	for _, e := range edits {
		t.Run(e.name, func(t *testing.T) {
			if code, _, stderr := gen(t, "--check", root); code != exitOK {
				t.Fatalf("the untouched tree: exit %d: %s", code, stderr)
			}
			put(t, root, rel, e.edit(good))
			code, _, stderr := gen(t, "--check", root)
			if code != exitStale || !strings.Contains(stderr, rel+" differs") {
				t.Fatalf("exit %d, stderr %q: want %d naming %s", code, stderr, exitStale, rel)
			}
			if read(t, root, rel) != e.edit(good) {
				t.Fatal("--check wrote a file")
			}
			put(t, root, rel, good)
		})
	}
	if err := os.Remove(filepath.Join(root, filepath.FromSlash(rel))); err != nil {
		t.Fatal(err)
	}
	if code, _, stderr := gen(t, "--check", root); code != exitStale || !strings.Contains(stderr, rel+" is missing") {
		t.Fatalf("missing file: exit %d, stderr %q", code, stderr)
	}
}

// Acceptance 3: no source fails, unless --allow-no-source (the Makefile, until S2b-2).
func TestNoSource(t *testing.T) {
	root := t.TempDir()
	put(t, root, "challenges/01-a/falco-rule.yaml", "type: trigger\nexpectedRules: [r]\n")
	put(t, root, "scenarios/legacy/scenario.yaml", legacyScenario)
	for _, args := range [][]string{{root}, {"--check", root}} {
		if code, _, stderr := gen(t, args...); code != exitFail || !strings.Contains(stderr, "no module.yaml or course.yaml") {
			t.Fatalf("%v: exit %d, stderr %q", args, code, stderr)
		}
		if code, _, stderr := gen(t, append([]string{"--allow-no-source"}, args...)...); code != exitOK {
			t.Fatalf("--allow-no-source %v: exit %d, stderr %q", args, code, stderr)
		}
	}
	if got := read(t, root, "scenarios/legacy/scenario.yaml"); got != legacyScenario {
		t.Fatalf("rewritten: %s", got)
	}
}

// An invalid source fails with exit 3 and writes no file, not even the valid ones.
func TestInvalidSource_WritesNothing(t *testing.T) {
	cases := []struct{ name, rel, body, want string }{
		{"course names a missing module", "scenarios/course-x/course.yaml", strings.Replace(courseYAML, "id: mod-b", "id: mod-q", 1), `module "mod-q" is not in the module pool`},
		{"both sources in one directory", "scenarios/mod-a/course.yaml", courseYAML, "holds both"},
		{"mission not in the pool", "scenarios/mod-b/module.yaml", moduleYAML("mod-b", "2", "03-c", "99-z"), `mission "99-z" is not a challenge of the pool`},
		{"an unknown key", "scenarios/mod-a/module.yaml", moduleYAML("mod-a", "1", "01-a") + "tactics: [x]\n", "tactics"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			root := newTree(t)
			put(t, root, c.rel, c.body)
			code, _, stderr := gen(t, root)
			if code != exitFail || !strings.Contains(stderr, c.want) {
				t.Fatalf("exit %d, stderr %q: want %d naming %q", code, stderr, exitFail, c.want)
			}
			for _, id := range []string{"mod-a", "mod-b", "course-x"} {
				if _, err := os.Stat(filepath.Join(root, "scenarios", id, "scenario.yaml")); !errors.Is(err, os.ErrNotExist) {
					t.Fatalf("scenarios/%s/scenario.yaml was written (%v)", id, err)
				}
			}
		})
	}
}

// --out is the one way Dockerfile.gen-scenarios writes (its export stage copies /gen): the
// files land under <out>/scenarios/<id>/, and nothing is written in the root.
func TestGenerate_OutDir(t *testing.T) {
	root, out := newTree(t), t.TempDir()
	if code, _, stderr := gen(t, "--out", out, root); code != exitOK {
		t.Fatalf("exit %d: %s", code, stderr)
	}
	if got := read(t, out, "scenarios/course-x/scenario.yaml"); got != goldenCourse {
		t.Fatalf("<out>/scenarios/course-x/scenario.yaml =\n%s\nwant\n%s", got, goldenCourse)
	}
	for _, id := range []string{"mod-a", "mod-b", "course-x"} {
		if _, err := os.Lstat(filepath.Join(root, "scenarios", id, "scenario.yaml")); !errors.Is(err, os.ErrNotExist) {
			t.Fatalf("scenarios/%s/scenario.yaml was written in the root (%v)", id, err)
		}
	}
	if got := read(t, root, "scenarios/legacy/scenario.yaml"); got != legacyScenario {
		t.Fatalf("rewritten: %s", got)
	}
	if _, err := os.Lstat(filepath.Join(out, "scenarios", "legacy")); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("a directory without a source was written under --out (%v)", err)
	}
}

// A symlink directly under scenarios/ is refused (exit 3); a generated path that is a
// symlink or a directory is not the generated file (--check, exit 1).
func TestSymlinkAndNotRegular(t *testing.T) {
	root := newTree(t)
	if err := os.Symlink(filepath.Join(root, "scenarios", "mod-a"), filepath.Join(root, "scenarios", "zz-link")); err != nil {
		t.Fatal(err)
	}
	if code, _, stderr := gen(t, root); code != exitFail || !strings.Contains(stderr, "zz-link is a symlink") {
		t.Fatalf("symlinked scenario directory: exit %d, stderr %q", code, stderr)
	}
	const rel = "scenarios/course-x/scenario.yaml"
	for _, name := range []string{"symlink", "directory"} {
		t.Run(name, func(t *testing.T) {
			root := newTree(t)
			if code, _, stderr := gen(t, root); code != exitOK {
				t.Fatalf("generate: exit %d: %s", code, stderr)
			}
			p := filepath.Join(root, filepath.FromSlash(rel))
			if err := os.Rename(p, p+".real"); err != nil {
				t.Fatal(err)
			}
			var err error
			if name == "symlink" {
				err = os.Symlink(p+".real", p) // the target holds the right bytes
			} else {
				err = os.Mkdir(p, 0o755)
			}
			if err != nil {
				t.Fatal(err)
			}
			if code, _, stderr := gen(t, "--check", root); code != exitStale || !strings.Contains(stderr, rel+" is not a regular file") {
				t.Fatalf("exit %d, stderr %q", code, stderr)
			}
		})
	}
}

