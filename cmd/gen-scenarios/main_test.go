// readerShape is the form the four shell readers of `challenges:` agree on, held strictly:
//   - challenges/gen-values.sh:301-313 scenario_challenge_ids (awk): opens at a line
//     matching ^challenges:, closes at the first line starting with a non-space, takes
//     each ^\s*-\s* line with a trailing #... and spaces cut;
//   - charts/ctf-user/validate-flags-file.sh:169-178: the same awk program;
//   - charts/ctf-user/assert-flag-isolation.sh:306-344 (bash, builtins): opens at a line
//     starting with challenges:, skips an empty line, takes an indented line starting
//     with - (# and spaces cut), closes at any other line;
//   - charts/ctf-user/deploy-user.sh:517-528 only tests that the file exists, and reads
//     the list through validate-flags-file.sh (:583) and assert-flag-isolation.sh (:1196);
//   - and a fifth, not shell: scripts/gen-attack-layer.py load_scenarios (:280-309) reads
//     the list with _yaml_block_list (:259-277: opens at ^challenges:\s*$, skips a blank
//     line, takes a line starting with -, closes at any other) and id / title with
//     _yaml_scalar (:233-238), which strips quotes and unescapes nothing: render refuses
//     a value it would read otherwise (TestRender_AttackReaderTitle).
//
// In this form (one line that is exactly "challenges:", then "  - <id>" lines of the
// challengeid grammar, no #, no quote, then a key at column 0; LF only) every reader
// takes exactly the ids, in order, and no other line opens a second block.
func readerShape(data string) ([]string, error) {
	if !strings.HasSuffix(data, "\n") || strings.ContainsAny(data, "\r\t") {
		return nil, errors.New("not LF-only text with a final newline and no tab")
	}
	lines := strings.Split(strings.TrimSuffix(data, "\n"), "\n")
	open := -1
	for i, l := range lines {
		if strings.HasPrefix(l, "challenges:") {
			if open >= 0 || l != "challenges:" {
				return nil, errors.New("a second, or a not bare, line starting with challenges:")
			}
			open = i
		}
	}
	if open < 0 {
		return nil, errors.New("no challenges: line")
	}
	var ids []string
	i := open + 1
	for ; i < len(lines) && strings.HasPrefix(lines[i], " "); i++ {
		id, ok := strings.CutPrefix(lines[i], "  - ")
		if !ok || !challengeid.Valid(id) {
			return nil, errors.New("line " + lines[i] + " is not \"  - <id>\"")
		}
		ids = append(ids, id)
	}
	if i < len(lines) && (lines[i] == "" || lines[i][0] == '#') {
		return nil, errors.New("the block is not closed by a key")
	}
	return ids, nil
}

// Acceptance 4: every generated file is in the readers' form and they read the composed
// list from it; the Go reader (catalog.LoadScenario) reads the same id and list.
func TestGenerated_ReaderShape(t *testing.T) {
	root := newTree(t)
	files, _, err := generate(root)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string][]string{
		"course-x": {"01-a", "02-b", "03-c"}, "mod-a": {"01-a", "02-b"}, "mod-b": {"03-c", "02-b"},
	}
	for _, f := range files {
		id := strings.Split(f.rel, "/")[1]
		got, err := readerShape(string(f.data))
		if err != nil || !slices.Equal(got, want[id]) {
			t.Fatalf("%s: shell readers' list %v (%v), want %v", f.rel, got, err, want[id])
		}
		put(t, root, f.rel, string(f.data))
		s, err := catalog.LoadScenario(filepath.Join(root, filepath.FromSlash(f.rel)))
		if err != nil || s.ID != id || !slices.Equal(s.Challenges, want[id]) {
			t.Fatalf("%s: LoadScenario = %+v, %v", f.rel, s, err)
		}
	}
	// The shape check can fail: each of these is a form D5 forbids.
	for _, bad := range []string{
		"challenges: [01-a]\nsource:\n",
		"challenges:\n  - 01-a # c\nsource:\n",
		"challenges:\n  - \"01-a\"\nsource:\n",
		"challenges:\n    - 01-a\nsource:\n",
		"challenges:\n  - 01-a\n\n  - 02-b\n",
		"challenges:\n  - 01-a\nchallenges:\n  - 02-b\n",
	} {
		if _, err := readerShape(bad); err == nil {
			t.Errorf("readerShape accepted %q", bad)
		}
	}
}

// scalar's value reads back as the string, on one line; the forms of the clear cases are
// pinned ("" = only the read-back is held).
func TestScalar(t *testing.T) {
	for in, want := range map[string]string{
		"Course X": "Course X", "2h": "2h", "a: b": `"a: b"`, "null": `"null"`, "x #y": `"x #y"`,
		"true": `"true"`, "12": `"12"`, "a\nb": `"a\nb"`, "": `""`,
		"- x": "", `"hi" there`: "", "<b> & c": "", "it's": "", "tab\there": "",
	} {
		got := scalar(in)
		var back map[string]string
		if err := yaml.Unmarshal([]byte("k: "+got+"\n"), &back); err != nil || back["k"] != in || strings.Contains(got, "\n") {
			t.Errorf("scalar(%q) = %s, reads back as %q (%v)", in, got, back["k"], err)
		}
		if want != "" && got != want {
			t.Errorf("scalar(%q) = %s, want %s", in, got, want)
		}
	}
}
