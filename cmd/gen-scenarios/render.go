package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"reflect"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/Qfour/falco-ctf-app/internal/catalog"
	"github.com/Qfour/falco-ctf-app/internal/catalog/challengeid"
)

// headerPrefix starts every file this generator writes (--check uses it to find one left
// in a directory whose source was removed).
const headerPrefix = "# GENERATED by gen-scenarios from "

// render is D5's scenario.yaml for c, generated from src (a slash path). The form is
// written here line by line, not left to a YAML emitter, because four shell readers and
// scripts/gen-attack-layer.py parse it by its lines (main_test.go names them): a header of
// comment lines (none starts with `challenges:`), then id, title, the one line
// `challenges:` followed by one `  - <id>` line per challenge (an id of the
// challengeid grammar: plain, no comment, no quote), then `source:`, a key at column 0
// that ends the block for every reader. LF only, one newline at the end. No tactics
// (D6) and no requirements (S3a).
//
// The bytes are decoded again, strictly, and must give c back; a value YAML would read
// otherwise is an error, not a file. So is an id or a title gen-attack-layer.py would read
// otherwise (attackRead).
func render(c catalog.Composed, src string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s%s — DO NOT EDIT\n", headerPrefix, src)
	b.WriteString("# Edit the source, not this file, then run make gen-scenarios.\n")
	for _, kv := range [][2]string{{"id", c.ID}, {"title", c.Title}} {
		v := scalar(kv[1])
		if got := attackRead(v); got != kv[1] {
			return nil, fmt.Errorf("%s %q would be read as %q by scripts/gen-attack-layer.py, which strips quotes and unescapes nothing: "+
				`use no \, no ", no control character and no ' at either end`, kv[0], kv[1], got)
		}
		fmt.Fprintf(&b, "%s: %s\n", kv[0], v)
	}
	b.WriteString("challenges:\n")
	for _, id := range c.Challenges {
		if !challengeid.Valid(id) {
			return nil, fmt.Errorf("challenge %q is not a challenge id (%s)", id, challengeid.Pattern)
		}
		fmt.Fprintf(&b, "  - %s\n", id)
	}
	fmt.Fprintf(&b, "source:\n  kind: %s\n  modules:\n", scalar(c.Source.Kind))
	for _, m := range c.Source.Modules {
		fmt.Fprintf(&b, "    - id: %s\n      version: %d\n", scalar(m.ID), m.Version)
		if m.Edition != "" {
			fmt.Fprintf(&b, "      edition: %s\n", scalar(m.Edition))
		}
	}
	var back catalog.Composed
	dec := yaml.NewDecoder(bytes.NewReader(b.Bytes()))
	dec.KnownFields(true)
	if err := dec.Decode(&back); err != nil {
		return nil, fmt.Errorf("the rendered file does not decode: %w", err)
	}
	if !reflect.DeepEqual(back, c) {
		return nil, fmt.Errorf("the rendered file decodes to %+v, not %+v", back, c)
	}
	return b.Bytes(), nil
}

// attackRead is the value scripts/gen-attack-layer.py's _yaml_scalar (:233-238, called by
// load_scenarios :295-301) takes from the line "<key>: v": v without the blanks around it,
// then without every " at either end, then without every ' at either end. It unescapes
// nothing, so a value it reads otherwise than YAML does is refused by render.
func attackRead(v string) string {
	return strings.Trim(strings.Trim(strings.TrimSpace(v), `"`), "'")
}

// scalar is s as a YAML value on one line: plain when YAML reads that plain text back as
// the string s, else double-quoted (a JSON string is a YAML double-quoted scalar).
func scalar(s string) string {
	var doc yaml.Node
	if !strings.ContainsAny(s, "\n\r") && yaml.Unmarshal([]byte("k: "+s+"\n"), &doc) == nil &&
		len(doc.Content) == 1 && len(doc.Content[0].Content) == 2 {
		v := doc.Content[0].Content[1]
		if v.Kind == yaml.ScalarNode && v.Style == 0 && v.ShortTag() == "!!str" && v.Value == s {
			return s
		}
	}
	var q bytes.Buffer
	enc := json.NewEncoder(&q)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s) // a string always encodes; invalid UTF-8 becomes U+FFFD, which the decode in render refuses
	return strings.TrimSuffix(q.String(), "\n")
}
